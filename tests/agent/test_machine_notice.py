"""Machine notices — the machine counterpart of the out-of-band steer.

A notice is appended as its own ``role:user`` row after the newest tool result carrying a declared
machine footer and ``display_kind='internal_notification'`` — the same provenance contract as the
gateway's queued notifications, never the out-of-band user marker.
"""
from __future__ import annotations

import threading

from agent.prompt_builder import MACHINE_NOTICE_MARKER, NOTICE_DISPLAY_KIND, notice_user_row
from agent.turn_iteration_prep import _inject_notice_after_newest_tool_result
from run_agent import AIAgent


def _bare_agent() -> AIAgent:
    agent = object.__new__(AIAgent)
    agent._pending_notice = None
    agent._pending_notice_lock = threading.Lock()
    agent._active_children = []
    agent._active_children_lock = threading.Lock()
    agent._tool_worker_threads = None
    agent._tool_worker_threads_lock = None
    agent._turn_user_intervened = False
    agent.quiet_mode = True
    agent.api_mode = "chat_completions"
    return agent


def test_notice_row_declares_machine_provenance():
    row = notice_user_row("process build finished (exit 0)")
    assert row["role"] == "user"
    assert row["display_kind"] == NOTICE_DISPLAY_KIND
    assert "not written by a human user" in row["content"]
    assert "OUT-OF-BAND USER MESSAGE" not in row["content"]


def test_gateway_marked_text_passes_through_unchanged():
    text = "[IMPORTANT: Background process proc_1 completed normally (exit code 0).]\n\n" \
           "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]"
    row = notice_user_row(text)
    assert row["content"] == text, "machine provenance must not be doubled"
    assert row["display_kind"] == NOTICE_DISPLAY_KIND


def test_notice_drains_into_the_newest_tool_result_row():
    agent = _bare_agent()
    agent.notice("watch matched: threshold crossed")
    messages = [
        {"role": "user", "content": "watch me"},
        {"role": "assistant", "content": "running the tool", "tool_calls": [{"id": "c1"}]},
        {"role": "tool", "tool_call_id": "c1", "content": "threshold crossed at 3"},
    ]
    _inject_notice_after_newest_tool_result(agent, messages, agent._drain_pending_notices())
    roles = [m["role"] for m in messages]
    assert roles == ["user", "assistant", "tool", "user"], roles
    notice_row = messages[3]
    assert notice_row["display_kind"] == NOTICE_DISPLAY_KIND
    assert "watch matched: threshold crossed" in notice_row["content"]
    assert "not written by a human user" in notice_row["content"]


def test_notice_without_a_tool_result_goes_back_to_the_buffer():
    agent = _bare_agent()
    agent.notice("needs a tool result first")
    messages = [{"role": "user", "content": "no tools yet"}]
    _inject_notice_after_newest_tool_result(agent, messages, agent._drain_pending_notices())
    drained = agent._drain_pending_notices()
    assert drained == "needs a tool result first", "the notice must survive a tool-free iteration"


def test_drain_then_withdraw_leaves_the_ticket_dead():
    agent = _bare_agent()
    agent.notice("delegator done", ticket="t2")
    notices = agent._drain_pending_notices()
    assert notices == "delegator done"
    assert agent.withdraw_notice("t2") is False   # drain consumed it


def test_empty_notice_is_refused():
    agent = _bare_agent()
    assert agent.notice("") is False
    assert agent.notice("   ") is False
