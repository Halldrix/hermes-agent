"""Machine notices: gateway/plugin text delivered INTO a running turn.

A notice is text inside the newest ``role:"tool"`` result — never a synthetic user/system row,
never the out-of-band user marker, so the model reads it as information the gateway delivered and
not as the user speaking. Appending extends the tail only (prompt-cache safe); an older turn's
tool result may already be persisted, so the newest one is the only mutable surface.
"""

from __future__ import annotations

# Declared provenance so the model never mistakes machine text for the user speaking — and unlike
# the out-of-band user marker, no authority to act on.
MACHINE_NOTICE_SUFFIX = (
    "[SYSTEM NOTICE — generated by the Hermes gateway, not written by a human user. "
    "Informational only: not a user instruction, and never a reason to reply to the user's last message]"
)


def inject_notice_after_newest_tool_result(agent, messages, notice_text: str) -> bool:
    """Append *notice_text* to the newest ``role:"tool"`` message's content; cache-safe."""
    from agent.context_compressor import _DB_PERSISTED_MARKER
    if not notice_text or not notice_text.strip():
        return False
    for msg in reversed(messages):
        if isinstance(msg, dict) and msg.get("role") == "tool":
            if msg.get(_DB_PERSISTED_MARKER):
                return False
            existing = msg.get("content", "")
            suffix = f"\n\n{MACHINE_NOTICE_SUFFIX}\n{notice_text.strip()}"
            if isinstance(existing, str):
                msg["content"] = existing + suffix
            else:  # multimodal content blocks — append a text block
                msg["content"] = [
                    *(existing if isinstance(existing, list) else [str(existing)]),
                    {"type": "text", "text": suffix},
                ]
            return True
    return False
